#!/usr/bin/env node
// Ensures mpvpaper is showing the video for the current prayer period. Idempotent - safe to run
// on login and on every timer tick (see docs/omarchy.md step 6, docs/wallpaper-crash-log.md).
// Always uses the clean (bannerless) scenes - no "prayer just started" text overlay, just the
// scene. (The bannered set in wallpaper-videos/ is still rendered by
// render-wallpaper-videos.mjs without --clean, but nothing plays it as a live wallpaper anymore.)
//
// Manual pin (see omarchy/extensions/menu.sh's Background submenu): `--pin <prayer>` pins the
// wallpaper to that prayer's scene, ignoring the real time, until `--auto` (or no flag) restores
// the normal real-time swap. The pin survives across timer ticks via a state file, so the
// once-a-minute timer doesn't fight a manual choice.
//
// Reimplements apps/web/src/lib/prayerClock.ts's currentPeriod() standalone: that file reads
// `location` at module scope, so it can't be imported directly from plain Node.

import { spawn, execSync } from 'node:child_process'
import { connect } from 'node:net'
import { mkdir, readFile, writeFile, unlink } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const VIDEO_DIR_CLEAN = path.join(__dirname, 'wallpaper-videos-clean')
const BASE_URL = process.env.DASHBOARD_URL ?? 'http://127.0.0.1:8080'
const IPC_SOCKET = '/tmp/mpvpaper-wallpaper.sock'
const STATE_DIR = path.join(process.env.HOME, '.cache', 'rpi-dashboard')
const STATE_FILE = path.join(STATE_DIR, 'wallpaper-period')
const PIN_FILE = path.join(STATE_DIR, 'wallpaper-pin')
const GLOW_CONF = path.join(process.env.HOME, '.config', 'hypr', 'wallpaper-glow.conf')

const PRAYERS = ['fajr', 'dhuhr', 'asr', 'maghrib', 'isha']

// Non-prayer scenery scenes (see omarchy/render-scenery-videos.mjs), pinnable the same way as a
// prayer but never chosen automatically - there's no "current scenery scene" to follow.
const SCENERY_SCENES = ['aqsa-sunset', 'farooq-wedding', 'haram-aerial', 'kazakh-meadow', 'madinah', 'night-mosque']
const PINNABLE = [...PRAYERS, ...SCENERY_SCENES]

// Recolors the Hyprland window shadow/glow (decoration.shadow, see
// ~/.config/omarchy/current/theme/hyprland.conf's $activeShadowColor) to match whichever prayer
// scene is currently the wallpaper.
//
// NOT each scene's theme "accent" (config/themes/*.json) - tried that first, but those are all
// clustered within about 12 degrees of hue ("warm gold"), tuned for on-screen pixel-art/text
// contrast rather than a room-glow palette. sunset (fajr) and madinah-maghrib (maghrib) even share
// the exact same accent hex, so two of the five prayers were visually indistinguishable. This is
// a separate, deliberately distinct palette instead, following the actual sky color across the
// day: cool dawn blue -> bright midday gold -> warm afternoon orange -> sunset rose -> night indigo.
const GLOW_COLORS = {
  fajr: '7fa8ff',
  dhuhr: 'ffd24a',
  asr: 'ff8c42',
  maghrib: 'ff5c7a',
  isha: '8a6fe8',
}

async function updateGlow(period) {
  const color = GLOW_COLORS[period]
  if (!color) return // scenery scene, not a prayer - leave the glow as whatever it last was
  const content = `# Generated by wallpaper-swap.mjs - do not edit by hand, overwritten every swap.
# Recolors the window shadow/glow to match the current prayer's time-of-day color.
decoration {
    shadow {
        color = rgb(${color})
        color_inactive = rgba(${color}77)
    }
}
`
  let existing
  try {
    existing = await readFile(GLOW_CONF, 'utf8')
  } catch {
    existing = undefined
  }
  if (existing === content) return // nothing to do

  await writeFile(GLOW_CONF, content)
  execSync('hyprctl reload', { stdio: 'ignore' })
}

// Same period logic as prayerClock.ts's currentPeriod(): Fajr runs until Dhuhr, Isha until the
// next Fajr.
function currentPeriod(times, now) {
  const at = (name) => {
    const t = times.find((x) => x.name === name)?.time
    return t ? new Date(t) : undefined
  }
  const fajr = at('fajr'), dhuhr = at('dhuhr'), asr = at('asr'), maghrib = at('maghrib'), isha = at('isha')
  if (!fajr || !dhuhr || !asr || !maghrib || !isha) return undefined
  if (now < fajr) return 'isha'
  if (now < dhuhr) return 'fajr'
  if (now < asr) return 'dhuhr'
  if (now < maghrib) return 'asr'
  if (now < isha) return 'maghrib'
  return 'isha'
}

function isMpvpaperRunning() {
  try {
    execSync('pgrep -x mpvpaper', { stdio: 'ignore' })
    return true
  } catch {
    return false
  }
}

function sendIpcCommand(command) {
  return new Promise((resolve, reject) => {
    const sock = connect(IPC_SOCKET, () => {
      sock.write(JSON.stringify({ command }) + '\n', (err) => {
        sock.end()
        err ? reject(err) : resolve()
      })
    })
    sock.on('error', reject)
  })
}

async function main() {
  await mkdir(STATE_DIR, { recursive: true })

  // --pin <prayer> / --auto update the pin file, then fall through to apply it immediately
  // (rather than waiting up to a minute for the next timer tick).
  const pinArg = process.argv.indexOf('--pin')
  if (pinArg !== -1) {
    const name = process.argv[pinArg + 1]
    if (!PINNABLE.includes(name)) throw new Error(`--pin: unknown prayer or scene "${name}"`)
    await writeFile(PIN_FILE, name)
  } else if (process.argv.includes('--auto')) {
    await unlink(PIN_FILE).catch(() => {}) // not pinned, fine
  }

  let pinned
  try {
    pinned = (await readFile(PIN_FILE, 'utf8')).trim()
    if (!PINNABLE.includes(pinned)) pinned = undefined
  } catch {
    pinned = undefined
  }

  let period
  if (pinned) {
    period = pinned
  } else {
    const res = await fetch(`${BASE_URL}/api/prayer/today`)
    if (!res.ok) throw new Error(`GET /api/prayer/today -> ${res.status}`)
    const { times } = await res.json()

    period = currentPeriod(times, new Date())
    if (!period || !PRAYERS.includes(period)) throw new Error(`Could not determine prayer period from: ${JSON.stringify(times)}`)
  }

  await updateGlow(period)

  const videoPath = path.join(VIDEO_DIR_CLEAN, `${period}.mp4`)

  // Omarchy's default swaybg claims the same layer-shell background layer mpvpaper uses.
  // Idempotent no-op if it's not running.
  try {
    execSync('pkill swaybg', { stdio: 'ignore' })
  } catch {
    // not running, fine
  }

  let lastPeriod
  try {
    lastPeriod = (await readFile(STATE_FILE, 'utf8')).trim()
  } catch {
    lastPeriod = undefined
  }

  const running = isMpvpaperRunning()

  if (running && lastPeriod === period) {
    return // nothing to do
  }

  if (running) {
    await sendIpcCommand(['loadfile', videoPath, 'replace'])
    // keep-open is set globally (see spawn below) so a still frame holds instead of flashing
    // black if timing is ever off - force unpause here in case that's left it paused.
    await sendIpcCommand(['set_property', 'pause', 'no'])
    console.log(`Swapped wallpaper to ${period}`)
  } else {
    const child = spawn(
      'mpvpaper',
      [
        // panscan=1.0: crop-to-fill instead of letterboxing. The videos are 1920x1080 (16:9);
        // eDP-1 is 3456x2160 (16:10), so fit-without-crop leaves black bars top/bottom.
        // No --auto-pause: it pauses whenever the wallpaper layer is covered/hidden, but its
        // resume detection isn't reliable and left it stuck paused (see
        // docs/wallpaper-crash-log.md). Always-on costs ~25% CPU (measured, a quarter of one
        // core on this 10-core machine) - reliability wins over that modest saving.
        '-o', `no-audio loop panscan=1.0 keep-open=yes input-ipc-server=${IPC_SOCKET}`,
        '*',
        videoPath,
      ],
      { detached: true, stdio: 'ignore' },
    )
    child.unref()
    console.log(`Launched mpvpaper with ${period}`)
  }

  await writeFile(STATE_FILE, period)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
